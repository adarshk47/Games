// Story Recall content in every language. Answers are option indices and are
// the same in every language (options keep the same order everywhere).
import 'mm_text.dart';

class StoryQ {
  const StoryQ(this.texts, this.optionTexts, this.answer);
  final MmL<String> texts; // lang -> question
  final MmL<List<String>> optionTexts; // lang -> 3 options
  final int answer; // index into options (same for every language)

  String get q => mmPick(texts);
  List<String> get options => mmPick(optionTexts);
}

class MmStory {
  const MmStory(this.emoji, this.titles, this.lineTexts, this.questions);
  final String emoji;
  final MmL<String> titles;
  final MmL<List<String>> lineTexts;
  final List<StoryQ> questions;

  String get title => mmPick(titles);
  List<String> get lines => mmPick(lineTexts);
}

